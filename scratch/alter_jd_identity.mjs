import 'dotenv/config';
import pg from 'pg';
const { Client } = pg;

const client = new Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

await client.query(`
  ALTER TABLE job_descriptions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
`).catch(e => console.log('Identity note:', e.message));

console.log('Made job_descriptions.id auto-generating identity.');
await client.end();

